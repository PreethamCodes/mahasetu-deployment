def init(path):
    values = local.read_env(path)
    for key in SECRETS:
        if not values.get(key):
            values[key] = local.token() + (local.token() if key in LONG else "")
    for key in BLANKS:
        values.setdefault(key, DEFAULTS.get(key, ""))
    path.write_text(HEADER + "".join(f"{k}={v}\n" for k, v in values.items()), encoding="utf-8")
    print(f"Wrote {path} (secrets are not printed). Fill the blanks, then run `settings <service>`.")


def runtime_url(schema, values):
    """Connection string for a schema's scoped login on its own database. A Supabase pooler wants login.<project ref>."""
    prefix = schema.upper() + "_DB_"
    host, port, name, tenant = (values.get(prefix + part, "") for part in ("HOST", "PORT", "NAME", "TENANT"))
    if not host or not port or not name:
        return ""
    login = local.LOGINS[schema] + ("." + tenant if tenant else "")
    password = quote(values[schema.upper() + "_LOGIN_PASSWORD"], safe="")
    if schema == "scholarship":  # Node: encrypt without verifying the host certificate unless you supply its CA
        return f"postgresql://{login}:{password}@{host}:{port}/{name}?sslmode=no-verify"
    return f"postgresql+psycopg://{login}:{password}@{host}:{port}/{name}?sslmode=require"


