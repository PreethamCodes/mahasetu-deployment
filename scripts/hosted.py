def settings(args):
    path = Path(args.env_file)
    if not path.is_file():
        sys.exit("Run `init` first: " + str(path))
    block = service_settings(args.service, local.read_env(path))
    missing = [k for k in REQUIRED[args.service] if not block.get(k)]
    if missing:
        sys.exit("Fill these in " + str(path) + " first (or the values they are built from): " + ", ".join(missing))
    for key, value in block.items():
        print(f"{key}={value}")


def ensure_storage_stand_in(conn):
    """For a PostgreSQL that is not Supabase but must hold a schema whose migration grants on Supabase's storage schema."""
    if conn.execute("SELECT to_regclass('storage.buckets')").fetchone()[0] is None:
        conn.execute("""CREATE SCHEMA IF NOT EXISTS storage;
            CREATE TABLE IF NOT EXISTS storage.buckets(id text PRIMARY KEY, name text, public boolean);
            CREATE TABLE IF NOT EXISTS storage.objects(id uuid PRIMARY KEY, bucket_id text REFERENCES storage.buckets);
            ALTER TABLE storage.objects ENABLE ROW LEVEL SECURITY;""")
        print("storage      created a minimal stand-in (this database is not Supabase)")


def admin_connection(schema):
    import psycopg
    name = schema.upper() + "_ADMIN_DATABASE_URL"
    url = os.environ.get(name, "")
    if not url:
        sys.exit(f"Set {name} in your shell (a session-mode or direct administrator connection string for the {schema} database).")
    parts = urlsplit(url)
    print(f"{schema}: {parts.hostname}")
    return (psycopg.connect(urlunsplit(parts._replace(scheme="postgresql")), autocommit=True, connect_timeout=15),
            urlunsplit(parts._replace(scheme="postgresql+psycopg")))


def apply(args):
    path = Path(args.env_file)
    if not path.is_file():
        sys.exit("Run `init` first: " + str(path))
    values = local.read_env(path)
    for schema in SCHEMAS:
        if args.only and args.only != schema:
            continue
        conn, migration = admin_connection(schema)
        with conn:
            if args.storage_stand_in and schema in ("scholarship", "mahasetu"):
                ensure_storage_stand_in(conn)
            local.migrate_and_seed(conn, migration, [schema])
            local.create_logins(conn, [schema], values)


def check(args):
    path = Path(args.env_file)
    values = local.read_env(path) if path.is_file() else {}
    targets = {"scholarship-portal": values.get("PORTAL_URL"), "mahasetu-dashboard": values.get("SITE_URL"),
               "mahasetu-core": values.get("CORE_URL"), "revenue-api": values.get("REVENUE_API_URL"),
               "examination-api": values.get("EXAMINATION_API_URL"), "university-api": values.get("UNIVERSITY_API_URL")}
    empty = [name for name, url in targets.items() if not url]
    if empty:
        sys.exit("No address in " + str(path) + " for: " + ", ".join(empty))
    pending, deadline = dict(targets), time.time() + args.wait
    while pending and time.time() < deadline:
        for name, url in list(pending.items()):
            try:
                with urllib.request.urlopen(url.rstrip("/") + "/health", timeout=20) as response:
                    if response.status == 200:
                        print(f"up    {name}")
                        del pending[name]
            except (urllib.error.URLError, OSError):
                pass
        if pending:
            time.sleep(5)
    for name in pending:
        print(f"DOWN  {name}")
    sys.exit(1 if pending else 0)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("command", choices=["init", "apply", "settings", "check"])
    parser.add_argument("service", nargs="?", choices=sorted(REQUIRED), help="with settings: which service")
    parser.add_argument("--env-file", default=str(DEFAULT_ENV))
    parser.add_argument("--only", choices=SCHEMAS, help="with apply: one database only")
    parser.add_argument("--storage-stand-in", action="store_true", help="with apply: create a minimal storage schema if absent")
    parser.add_argument("--wait", type=int, default=240, help="with check: seconds to wait for sleeping services")
    args = parser.parse_args()
    if args.command == "settings" and not args.service:
        parser.error("settings needs a service name")
    {"init": lambda a: init(Path(a.env_file)), "apply": apply, "settings": settings, "check": check}[args.command](args)


if __name__ == "__main__":
    main()
