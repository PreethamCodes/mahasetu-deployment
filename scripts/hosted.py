"""Prepare and check a hosted synthetic demonstration with a completely separate database for each service.

  python scripts/hosted.py init                   create .env.hosted: generated synthetic secrets plus blanks for your addresses
  python scripts/hosted.py apply [--only NAME]    migrate, seed and create the scoped login on each hosted database
  python scripts/hosted.py settings SERVICE       print the environment settings to enter for one hosted service
  python scripts/hosted.py check [--wait 240]     wake every service and wait until each health address answers

Services: scholarship-portal, mahasetu-dashboard, mahasetu-core, revenue-api, examination-api, university-api.

Five databases, one per government service, so no service shares a server, a login or a network path with another:
  scholarship  Supabase project 1 (database plus the Auth and Storage the portal uses)
  mahasetu     Supabase project 2 (Core; its first migration needs the storage schema that Supabase provides)
  revenue, examination, university   one free Neon project each (or any other PostgreSQL)

`apply` needs an administrator connection to each database in your shell, never in a file this script writes:
  <SCHEMA>_ADMIN_DATABASE_URL for SCHOLARSHIP, MAHASETU, REVENUE, EXAMINATION and UNIVERSITY. Use a session-mode or direct
  string (Supabase session pooler; Neon direct, with pooling off): a transaction-mode pooler cannot run migrations.
  Add --storage-stand-in only for a database that is not Supabase but must hold the scholarship or mahasetu schema.
This script only orchestrates: every schema is migrated and seeded by its owner's own Alembic chain and db/seed.sql, exactly
as for the local database. .env.hosted is ignored by Git. Settings printed by `settings` contain secrets; enter them in the
host's dashboard and keep them out of chat and commits.
"""
