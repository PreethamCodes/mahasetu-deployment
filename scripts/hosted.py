"""Prepare and check a hosted synthetic demonstration: Supabase for the databases, any container host for the services.

  python scripts/hosted.py init                   create .env.hosted: generated synthetic secrets plus blanks for your addresses
  python scripts/hosted.py apply [--only NAME]    migrate, seed and create scoped logins on the hosted database(s)
  python scripts/hosted.py settings SERVICE       print the environment settings to enter for one hosted service
  python scripts/hosted.py check [--wait 240]     wake every service and wait until each health address answers

Services: scholarship-portal, mahasetu-dashboard, mahasetu-core, revenue-api, examination-api, university-api.

Layout for two free Supabase projects (the free plan allows two active projects):
  project "scholarship": the scholarship schema, plus Supabase Auth and Storage for applicant sign-in and documents
  project "mahasetu":    mahasetu (Core) and the revenue, examination and university schemas, each with its own login

`apply` needs an administrator connection to each project in your shell, never in a file this script writes:
  SCHOLARSHIP_ADMIN_DATABASE_URL and MAHASETU_ADMIN_DATABASE_URL (use Supabase's session-mode or direct string; the
  transaction-mode pooler cannot run migrations). This script only orchestrates: every schema is migrated and seeded by
  its owner's own Alembic chain and db/seed.sql, exactly as for the local database. .env.hosted is ignored by Git.
Settings printed by `settings` contain secrets; enter them in the host's dashboard and keep them out of chat and commits.
"""
import argparse
import os
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path
from urllib.parse import quote, urlsplit, urlunsplit

sys.path.insert(0, str(Path(__file__).resolve().parent))
import bootstrap_local_db as local  # noqa: E402

DEFAULT_ENV = local.DEPLOY / ".env.hosted"
PROJECTS = {  # project -> schemas it holds
    "scholarship": ["scholarship"],
    "mahasetu": ["mahasetu", "revenue", "examination", "university"],
}
HEADER = ("# Generated by scripts/hosted.py. Synthetic secrets plus your own addresses; never commit.\n"
          "# Fill every blank, then run `python scripts/hosted.py settings <service>` for each hosted service.\n")
SECRETS = ["SCHOLARSHIP_LOGIN_PASSWORD", "MAHASETU_LOGIN_PASSWORD", "REVENUE_LOGIN_PASSWORD", "EXAMINATION_LOGIN_PASSWORD",
           "UNIVERSITY_LOGIN_PASSWORD", "REVENUE_USER", "REVENUE_PASSWORD", "EXAMINATION_API_KEY", "UNIVERSITY_CLIENT_ID",
           "UNIVERSITY_CLIENT_SECRET", "UNIVERSITY_SIGNING_KEY", "DASHBOARD_CLIENT_TOKEN", "OTP_HASH_KEY",
           "REQUESTER_TOKEN_SCHOLARSHIP"]
LONG = {"UNIVERSITY_SIGNING_KEY", "OTP_HASH_KEY"}
# Left blank on purpose: only you know them. Addresses are the public https addresses your host gives each service.
BLANKS = ["PORTAL_URL", "SITE_URL", "CORE_URL", "REVENUE_API_URL", "EXAMINATION_API_URL", "UNIVERSITY_API_URL",
          "SCHOLARSHIP_DB_HOST", "SCHOLARSHIP_DB_PORT", "SCHOLARSHIP_DB_TENANT", "MAHASETU_DB_HOST", "MAHASETU_DB_PORT",
          "MAHASETU_DB_TENANT", "SUPABASE_URL", "SUPABASE_PUBLISHABLE_KEY", "SUPABASE_STORAGE_KEY"]
PROJECT_OF = {schema: project for project, schemas in PROJECTS.items() for schema in schemas}
REQUIRED = {
    "scholarship-portal": ["DATABASE_URL", "SUPABASE_URL", "SUPABASE_PUBLISHABLE_KEY", "SCHOLARSHIP_STORAGE_KEY",
                           "MAHASETU_CORE_URL", "MAHASETU_SITE_URL", "MAHASETU_REQUESTER_TOKEN"],
    "mahasetu-dashboard": ["CORE_API_URL", "DASHBOARD_CLIENT_TOKEN"],
    "mahasetu-core": ["DATABASE_URL", "DASHBOARD_CLIENT_TOKEN", "OTP_HASH_KEY", "REQUESTER_TOKEN_SCHOLARSHIP", "REVENUE_URL",
                      "EXAMINATION_URL", "UNIVERSITY_URL", "REVENUE_USER", "REVENUE_PASSWORD", "EXAMINATION_API_KEY",
                      "UNIVERSITY_CLIENT_ID", "UNIVERSITY_CLIENT_SECRET", "RETURN_URL_DEMO_PMS"],
    "revenue-api": ["DATABASE_URL", "REVENUE_USER", "REVENUE_PASSWORD"],
    "examination-api": ["DATABASE_URL", "EXAMINATION_API_KEY"],
    "university-api": ["DATABASE_URL", "UNIVERSITY_CLIENT_ID", "UNIVERSITY_CLIENT_SECRET", "UNIVERSITY_SIGNING_KEY"],
}


def init(path):
    values = local.read_env(path)
    for key in SECRETS:
        if not values.get(key):
            values[key] = local.token() + (local.token() if key in LONG else "")
    for key in BLANKS:
        values.setdefault(key, "")
    path.write_text(HEADER + "".join(f"{k}={v}\n" for k, v in values.items()), encoding="utf-8")
    print(f"Wrote {path} (secrets are not printed). Fill the blanks, then run `settings <service>`.")


def runtime_url(schema, values):
    """Connection string for a schema's scoped login on its hosted project. Supabase poolers want login.<project>."""
    project = PROJECT_OF[schema].upper()
    host, port, tenant = values.get(project + "_DB_HOST", ""), values.get(project + "_DB_PORT", ""), values.get(project + "_DB_TENANT", "")
    if not host or not port:
        return ""
    login = local.LOGINS[schema] + ("." + tenant if tenant else "")
    password = quote(values[schema.upper() + "_LOGIN_PASSWORD"], safe="")
    if schema == "scholarship":  # Node: encrypt without verifying the host certificate unless you supply its CA
        return f"postgresql://{login}:{password}@{host}:{port}/postgres?sslmode=no-verify"
    return f"postgresql+psycopg://{login}:{password}@{host}:{port}/postgres?sslmode=require"


