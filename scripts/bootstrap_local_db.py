"""Prepare the local Compose database for a synthetic demonstration.

  python scripts/bootstrap_local_db.py init    create .env.local-db with generated synthetic credentials
  python scripts/bootstrap_local_db.py apply   migrate and seed every schema, then create scoped logins

`init` needs no database. `apply` needs the local-db service to be healthy. The script only orchestrates:
each schema is migrated by its owner's Alembic chain and seeded by its owner's db/seed.sql, exactly as
documented in that repository. Running either command again is safe and keeps existing credentials.
Requires the packages in tests/requirements.txt. The generated file is ignored by Git; never commit it.
"""
import argparse
import os
import secrets
import subprocess
import sys
from pathlib import Path
from urllib.parse import quote

ROOT = Path(__file__).resolve().parents[2]
DEPLOY = ROOT / "mahasetu-deployment"
DEFAULT_ENV = DEPLOY / ".env.local-db"
# schema -> owning repository. Order matters only for readability; schemas are independent.
OWNERS = {"scholarship": "scholarship-portal", "revenue": "revenue-service",
          "examination": "examination-service", "university": "university-service",
          "mahasetu": "mahasetu-core"}
# schema -> login role. Each login inherits only that schema's NOLOGIN runtime role.
LOGINS = {"scholarship": "scholarship_app", "revenue": "revenue_app", "examination": "examination_app",
          "university": "university_app", "mahasetu": "mahasetu_app"}
HEADER = ("# Generated by scripts/bootstrap_local_db.py. Synthetic local credentials only; never commit.\n"
          "# Use with: docker compose --env-file .env.local-db --profile local-db ...\n"
          "# Applicant sign-in and storage default to the laptop-only local-identity service. To use a hosted Supabase\n"
          "# project instead, replace SCHOLARSHIP_SUPABASE_URL, SCHOLARSHIP_PUBLISHABLE_KEY and SCHOLARSHIP_STORAGE_KEY.\n")


def read_env(path):
    values = {}
    if path.is_file():
        for line in path.read_text(encoding="utf-8").splitlines():
            if line.strip() and not line.lstrip().startswith("#") and "=" in line:
                key, _, value = line.partition("=")
                values[key.strip()] = value.strip()
    return values


def token():
    return secrets.token_hex(24)


def desired(values):
    """Fill every missing setting; never replace an existing one."""
    out = dict(values)

    def keep(key, factory):
        out.setdefault(key, factory() if callable(factory) else factory)

    keep("LOCAL_DB_PASSWORD", token)
    keep("LOCAL_DB_PORT", "5433")
    for schema, login in LOGINS.items():
        keep(schema.upper() + "_LOGIN_PASSWORD", token)
    # Container-side addresses: the database is reachable as local-db:5432 inside Compose.
    for schema, login in LOGINS.items():
        password = quote(out[schema.upper() + "_LOGIN_PASSWORD"], safe="")
        driver = "postgresql://" if schema == "scholarship" else "postgresql+psycopg://"
        name = {"mahasetu": "CORE"}.get(schema, schema.upper())
        keep(name + "_DATABASE_URL", f"{driver}{login}:{password}@local-db:5432/mahasetu")
    keep("REVENUE_USER", token)
    keep("REVENUE_PASSWORD", token)
    keep("EXAMINATION_API_KEY", token)
    keep("UNIVERSITY_CLIENT_ID", token)
    keep("UNIVERSITY_CLIENT_SECRET", token)
    keep("UNIVERSITY_SIGNING_KEY", lambda: token() + token())
    keep("DASHBOARD_CLIENT_TOKEN", token)  # held only by the MahaSetu website's server
    keep("OTP_HASH_KEY", lambda: token() + token())
    keep("REQUESTER_TOKEN_SCHOLARSHIP", token)  # the Scholarship portal's server credential for Core
    keep("CORE_ENVIRONMENT", "development")
    keep("OTP_DEMO_DISCLOSURE", "enabled")  # lets the website show the one-time code; refused in production
    keep("DASHBOARD_COOKIE_SECURE", "false")  # loopback HTTP demonstration only
    keep("DEMO_MESSAGE_INBOX", "enabled")
    keep("PORTAL_DEMO_ACCESS", "enabled")
    keep("SCHOLARSHIP_COOKIE_SECURE", "false")  # loopback HTTP demonstration only
    # Laptop-only stand-in for Supabase Auth and Storage (scholarship-portal/tools/local-identity). It is reached only by
    # the Scholarship portal's server, as local-identity:9999 inside Compose.
    keep("SCHOLARSHIP_SUPABASE_URL", "http://local-identity:9999")
    keep("SCHOLARSHIP_PUBLISHABLE_KEY", token)
    keep("SCHOLARSHIP_STORAGE_KEY", token)
    return out


def init(path):
    existed = path.is_file()
    values = desired(read_env(path))
    path.write_text(HEADER + "".join(f"{k}={v}\n" for k, v in values.items()), encoding="utf-8")
    print(("Updated " if existed else "Created ") + str(path) + " (credentials are not printed).")


def connect(args, values):
    import psycopg
    password = os.environ.get("LOCAL_DB_PASSWORD") or values["LOCAL_DB_PASSWORD"]
    return psycopg.connect(host=args.host, port=int(args.port or values["LOCAL_DB_PORT"]), user=args.user,
                           dbname=args.database, password=password, autocommit=True, connect_timeout=5)


def migrate_and_seed(conn, migration_url, schemas):
    """Run each owner's Alembic chain and seed file for the given schemas. Works on any PostgreSQL reachable by conn."""
    for schema in schemas:
        repo = OWNERS[schema]
        env = dict(os.environ, MIGRATION_DATABASE_URL=migration_url)
        subprocess.run([sys.executable, "-m", "alembic", "upgrade", "head"], cwd=ROOT / repo, env=env, check=True,
                       stdout=subprocess.DEVNULL)
        conn.execute((ROOT / repo / "db/seed.sql").read_text(encoding="utf-8"))
        revision = conn.execute(f"SELECT version_num FROM {schema}.alembic_version").fetchone()[0]
        print(f"{schema:12} migrated to {revision} and seeded")


def create_logins(conn, schemas, values):
    """One login per schema that inherits only that schema's NOLOGIN runtime role."""
    from psycopg import sql
    for schema in schemas:
        login = LOGINS[schema]
        password = values[schema.upper() + "_LOGIN_PASSWORD"]
        exists = conn.execute("SELECT 1 FROM pg_roles WHERE rolname=%s", (login,)).fetchone()
        statement = "ALTER ROLE {} LOGIN PASSWORD {}" if exists else "CREATE ROLE {} LOGIN PASSWORD {}"
        conn.execute(sql.SQL(statement).format(sql.Identifier(login), sql.Literal(password)))
        conn.execute(sql.SQL("GRANT {} TO {}").format(sql.Identifier(schema + "_runtime"), sql.Identifier(login)))
    print("Created or refreshed " + str(len(schemas)) + " scoped logins. Each inherits only its own runtime role.")


def apply(args):
    path = Path(args.env_file)
    if not path.is_file():
        sys.exit("Run `init` first: " + str(path))
    values = desired(read_env(path))
    with connect(args, values) as conn:
        # Hosted Supabase provides the storage schema. A plain PostgreSQL container needs a minimal stand-in.
        conn.execute("""CREATE SCHEMA IF NOT EXISTS storage;
            CREATE TABLE IF NOT EXISTS storage.buckets(id text PRIMARY KEY, name text, public boolean);
            CREATE TABLE IF NOT EXISTS storage.objects(id uuid PRIMARY KEY, bucket_id text REFERENCES storage.buckets);
            ALTER TABLE storage.objects ENABLE ROW LEVEL SECURITY;""")
        migration_url = "postgresql+psycopg://{}:{}@{}:{}/{}".format(
            quote(args.user, safe=""), quote(os.environ.get("LOCAL_DB_PASSWORD") or values["LOCAL_DB_PASSWORD"], safe=""),
            args.host, int(args.port or values["LOCAL_DB_PORT"]), args.database)
        migrate_and_seed(conn, migration_url, list(OWNERS))
        create_logins(conn, list(LOGINS), values)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("command", choices=["init", "apply"])
    parser.add_argument("--env-file", default=str(DEFAULT_ENV))
    parser.add_argument("--host", default="127.0.0.1", help="Database host as seen from this machine")
    parser.add_argument("--port", help="Database port (default: LOCAL_DB_PORT from the env file)")
    parser.add_argument("--user", default="postgres")
    parser.add_argument("--database", default="mahasetu")
    args = parser.parse_args()
    init(Path(args.env_file)) if args.command == "init" else apply(args)


if __name__ == "__main__":
    main()
